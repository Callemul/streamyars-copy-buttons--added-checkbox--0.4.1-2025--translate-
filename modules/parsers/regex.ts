// ЄДИНЕ ДЖЕРЕЛО ПРАВДИ ДЛЯ REGEX-ПАТЕРНІВ ПАРСИНГУ

/**
 * Регулярний вираз для виявлення рядка, що складається виключно з emoji-цифр (напр. 1️⃣, 🔟)
 */
export const EMOJI_NUMBER_LINE_REGEX = /^(?:\d+\uFE0F?\u20E3|🔟)+\s*$/;

/**
 * Регулярний вираз для виявлення наявності хоча б однієї emoji-цифри у тексті
 */
export const EMOJI_NUMBER_CONTAINS_REGEX = /(?:\d+\uFE0F?\u20E3|🔟)/;

/**
 * Регулярний вираз для виявлення розділювачів/заголовків у форматованій тексті питань
 */
export const TELEGRAM_HEADER_MARKER_REGEX = /❓❓❓|🙏+|(?:\d+\uFE0F?\u20E3|🔟)/iu;

/**
 * Регулярний вираз для розбиття секцій молитов у тексті
 * Розбиває за заголовками привіду типу "🙏 МОЛИТВА" або "🙏 ПРОХАННЯ".
 * Дублікувався попередньо в banner_creator.ts та telegram_parser.ts.
 */
export const PRAYER_SECTION_SPLIT_REGEX = /(?:^|\r?\n)(?:\s*|\[\d{2}\.\d{2}\.\d{4}\s+\d{2}:\d{2}\]\s*[^:\r\n]+:\s*)🙏+[^\r\n]*(?:МОЛИТ|ПРОХАН)[^\r\n]*/iu;

/**
 * Регулярний вираз для визначення, чи рядок є початком питання.
 * Виявляє стандартні нумеровані питання (1. / 1), emoji-нумеровані (1️⃣, 🔟),
 * та підпункти з 🔹. Використовує EMOJI_NUMBER_CONTAINS_REGEX та StandardNumberRegex.
 */
export const STANDARD_NUMBER_REGEX = /\d+[.)]/;
export const STANDARD_NUMBER_START_REGEX = /(?:^|\s)\d+[.)]+(?!\d)/;
export const QUESTION_START_REGEX = /^(?:\d+[.)]|(?:\d+\uFE0F?\u20E3|🔟)|🔹)/;

/**
 * Регулярний вираз для розбиття тексту на питання за межами:
 * стандартні нумеровані (1. / 1), emoji-номеровані (1️⃣, 🔟), підпункти 🔹.
 */
export const QUESTION_SPLIT_REGEX = /(?:^|\s)(?=\d+[.)])|(?:^|\s)(?=(?:\d+\uFE0F?\u20E3|🔟))|(?=🔹)/;

/**
 * Регістр розрізняє розділи за початковими символами (❓, 🙏, або назви секцій)
 */
export const SECTION_HEADER_SPLIT_REGEX = /(?:^|\r?\n)(?=[❓🙏]|Вопросы к|Вопросы на|Предложения по|Саша, привет|Виталик, привет)/iu;

/**
 * Заголовки експорту Telegram: "Ім'я, [10.07.2026 20:44]"
 */
export const TG_HEADER_A_REGEX = /^.+?,\s*\[\d{2}\.\d{2}\.\d{4} \d{2}:\d{2}\]\s*$/;

/**
 * Заголовки експорту Telegram: "[10.07.2026 20:44] @User: Text"
 */
export const TG_HEADER_B_REGEX = /^\[\d{2}\.\d{2}\.\d{4} \d{2}:\d{2}\]\s*([^:\n]+)(?::\s*(.*))?$/;

/**
 * Очищення системних заголовків Telegram з часом
 */
export const TG_HEADER_CLEANUP_REGEX = /(?:^|\r?\n)\s*\[\d{2}\.\d{2}\.\d{4}\s+\d{2}:\d{2}\](?:[^\r\n:]*:\s*|[^\r\n]*(?=\r?\n|$))/g;

/**
 * Відносні мітки часу Telegram (напр. "щойно", "5 хвилин тому", "2 hours ago")
 */
export const RELATIVE_TIME_LINE_REGEX = /^(?:щойно|только\s*что|just\s*now)$|^\d+\s*(?:секунд[аиу]?|сек\.?|хвилин[аиу]?|хв\.?|минут[аыу]?|мин\.?|час(?:а|ів|ов|и|у)?|ч\.?|годин[аи]?|год\.?|hours?|hrs?|minutes?|mins?|seconds?|secs?)\s*(?:тому|назад|ago)?\.{0,3}$/i;

/**
 * Регулярний вираз для видалення суфікса автора або примітки в кінці питання.
 * Видаляє як закриті дужки в кінці: ` (Автор)`, так і незакриті: ` ( Автор 1 , Автор 2`
 */
export const QUESTION_AUTHOR_SUFFIX_REGEX = /\s*\([^)]*\)?\s*$/;